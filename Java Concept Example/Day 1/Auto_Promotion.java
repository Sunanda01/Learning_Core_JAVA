class Auto_Promotion
{
	public static void main(String[] args)
	{		
		System.out.println(10);			//10
		System.out.println(10.5);		//10.5
		System.out.println(10+20);			//30
		System.out.println(10+20.5);	   	//30.5 => Autopromotion
		System.out.println(10+" Sunanda");  //10 Sunanda => Autopromotion => String concatenation
		System.out.println();				//nothing will be printed, cursor moved to next line
		//System.out.print();				//CTE => method not found	
	}
} 